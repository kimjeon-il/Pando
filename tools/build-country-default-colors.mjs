import { readFileSync, writeFileSync } from 'node:fs';

// The approved research table owns the palette and its source provenance.
const sourceUrl = new URL('../docs/research/country-default-colors.json', import.meta.url);
const outputUrl = new URL('../assets/js/modules/country-default-colors.js', import.meta.url);
const source = JSON.parse(readFileSync(sourceUrl, 'utf8'));
if (source.status !== 'confirmed') throw new Error('국가 기본색이 확정되지 않았습니다.');
const entries = [
  ...source.baseCountries.map(row => [row.id, row.color]),
  ...source.historicalCountries.map(row => [row.libraryId, row.color]),
];
const ids = new Set();
for (const [id, color] of entries) {
  if (!id || ids.has(id)) throw new Error(`국가 기본색 ID가 비어 있거나 중복됩니다: ${id}`);
  if (color !== null && !/^#[0-9a-f]{6}$/i.test(color)) throw new Error(`국가 기본색이 올바르지 않습니다: ${id}`);
  ids.add(id);
}
if (source.baseCountries.length !== source.inventory.baseCountryCount
  || source.historicalCountries.length !== source.inventory.historicalCountryCount
  || entries.filter(([, color]) => color !== null).length !== source.inventory.assignedColorCount
  || entries.filter(([, color]) => color === null).length !== source.inventory.unassignedColorCount) {
  throw new Error('국가 기본색 목록과 확정 수량이 일치하지 않습니다.');
}
entries.sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0);
const output = '// Generated by tools/build-country-default-colors.mjs. Do not edit manually.\n'
  + '// Source: docs/research/country-default-colors.json; null means no intrinsic paint.\n'
  + `export const COUNTRY_DEFAULT_COLORS = Object.freeze(${JSON.stringify(Object.fromEntries(entries.map(([id, color]) => [id, color?.toLowerCase() ?? null])), null, 2)});\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(outputUrl, 'utf8') !== output) throw new Error('국가 기본색 표시 자료를 다시 생성하세요.');
} else writeFileSync(outputUrl, output);
console.log(`Country default colors: ${entries.length} identities, ${source.inventory.assignedColorCount} assigned.`);
