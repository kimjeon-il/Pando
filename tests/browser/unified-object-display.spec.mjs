import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
import {gotoEditor} from './helpers/editor-entry.mjs';
for(const renderer of ['webgl','canvas'])test(`one object menu governs roots, children and regions in ${renderer}`,async({page})=>{
 test.setTimeout(150000);const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.route('**/modules/app-domain-assembly.js*',async route=>{
  const body=(await(await route.fetch()).text()).replace('dependencies = ports;','dependencies = ports;window.__displayPorts=ports;window.__displayDomain=()=>projectDomain;');
  await route.fulfill({contentType:'text/javascript',body});
 });
 await gotoEditor(page,renderer==='canvas'?'/?renderer=canvas':'/');
 await expect(page.locator('#app')).toHaveAttribute('data-readiness',/editable|enhanced/,{timeout:90000});
 const seed=JSON.parse(readFileSync(new URL('../fixtures/timeline-exchange/complex.json',import.meta.url)));
 seed.projectSetup={initialMonth:'1914-06',sourceMode:'empty',timelineRange:null,initialMapBounds:{west:-5,east:20,south:-5,north:20}};
 seed.projectSetup.initialMonth='1914-06';
 await page.evaluate(seed=>window.__displayDomain().load(seed),seed);
 await expect.poll(()=>page.evaluate(()=>window.__displayPorts.projectState.state.timelineCursor)).toBe('1914-06');
 await expect(page.locator('#editorTimelineContext')).toContainText('1914년 6월');
 const before=await page.evaluate(()=>window.__displayDomain().snapshot());
 const items=()=>page.evaluate(()=>window.__displayPorts.objectCatalogView.listObjectSearchItems('objects').map(item=>item.id));
 expect(new Set(await items())).toEqual(new Set(['A','B','C','R']));
 await page.locator('#mapDisplayBtn').click();
 await expect(page.locator('[data-map-display-group="objects"]')).toHaveCount(1);
 await expect(page.locator('#countriesVisible,#subunitsVisible,#regionsVisible,#generalDisplayOptions')).toHaveCount(0);
 await page.locator('[data-map-display-row="objects"]').hover();
 await expect(page.locator('#layerStylePanel-objects')).toBeVisible();
 await page.locator('label').filter({has:page.locator('#objectsVisible')}).click();
 await expect.poll(items).toEqual([]);
 expect(await page.evaluate(()=>window.__displayDomain().snapshot())).toEqual(before);
 await page.locator('[data-map-display-row="objects"]').hover();
 await expect(page.locator('#layerStylePanel-objects')).toBeVisible();
 await page.locator('label').filter({has:page.locator('#objectsVisible')}).click();
 await page.locator('[data-map-display-row="objects"]').hover();
 await expect(page.locator('#layerStylePanel-objects')).toBeVisible();
 for(const id of ['objectNamesVisible','objectFlagsVisible'])await page.locator('label').filter({has:page.locator('#'+id)}).click();
 await expect.poll(()=>page.evaluate(()=>window.__displayPorts.projectState.state.layerVisibility.objectNames)).toBe(false);
 expect(await page.evaluate(()=>window.__displayPorts.projectState.state.layerVisibility.objectFlags)).toBe(false);
 expect(await page.evaluate(()=>window.__displayDomain().snapshot())).toEqual(before);
 const opacity=page.locator('[data-layer-style-opacity="objects"]');
 await opacity.focus();await opacity.press('Home');for(let i=0;i<40;i++)await opacity.press('ArrowRight');await opacity.press('Tab');
 await expect.poll(()=>page.evaluate(()=>window.__displayDomain().snapshot().layerPresentation.styles.objects.opacity)).toBe(.4);
 const changed=await page.evaluate(()=>window.__displayDomain().snapshot());
 expect(changed.territorialEntities).toEqual(before.territorialEntities);expect(changed.timelineRecords).toEqual(before.timelineRecords);expect(changed.geometries).toEqual(before.geometries);
 expect(Object.keys(changed.layerPresentation.styles).filter(key=>['objects','countries','subunits','regions'].includes(key))).toEqual(['objects']);
 await page.locator('#mapDisplayBtn').click();
 await page.locator('[data-map-display-row="objects"]').hover();
 await expect(page.locator('#layerStylePanel-objects')).toBeVisible();
 await page.screenshot({path:`.superpowers/sdd/2026-10-19-unified-object-display/${renderer}.png`});
 expect(errors).toEqual([]);
});
