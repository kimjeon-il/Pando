import test from 'node:test';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {mkdtempSync,mkdirSync,writeFileSync,readFileSync,rmSync,unlinkSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join,dirname} from 'node:path';
import {buildHistoryRetentionManifest,rewriteHistory} from '../../tools/library-history.mjs';

test('selected refs retain source history, remove superseded generated bytes and exclude private refs',async t=>{
  const base=mkdtempSync(join(tmpdir(),'pando-retention-fixture-'));
  t.after(()=>rmSync(base,{recursive:true,force:true}));
  const source=join(base,'source'),target=join(base,'clean.git');mkdirSync(source);
  const git=(root,args,input)=>execFileSync('git',['-C',root,'-c','gc.auto=0','-c','core.autocrlf=false',...args],{input,encoding:'utf8',stdio:['pipe','pipe','pipe']}).trim();
  const put=(path,value)=>{mkdirSync(dirname(join(source,path)),{recursive:true});writeFileSync(join(source,path),value);};
  const commit=()=>{git(source,['add','.']);git(source,['commit','-qm','edition']);};
  git(source,['init','-q','-b','main']);git(source,['config','user.name','Fixture']);git(source,['config','user.email','fixture@example.invalid']);
  put('src/input.txt','source v1');put('generated.bin','old generated');put('retired.bin','retired bytes');commit();
  const sourceOld=git(source,['rev-parse','HEAD:src/input.txt']),old=git(source,['rev-parse','HEAD:generated.bin']);
  put('src/input.txt','source v2');put('generated.bin','current generated');commit();
  const current=git(source,['rev-parse','HEAD:generated.bin']);git(source,['branch','work/live']);
  put('generated.bin','unused generated');commit();git(source,['branch','private']);
  const manifest=buildHistoryRetentionManifest({keepPaths:['src/input.txt','generated.bin'],indexes:[],allowedBlobIds:{'generated.bin':[current]}});
  await rewriteHistory({source,target,manifest,refs:['refs/heads/main','refs/heads/work/live'],filterRepoPath:process.env.PANDO_HISTORY_FILTER_REPO,pythonPath:process.env.PANDO_HISTORY_PYTHON});
  assert.equal(git(target,['ls-tree','--name-only','main','--','generated.bin']),'');
  assert.equal(git(target,['rev-parse','work/live:generated.bin']),current);
  assert.equal(git(target,['for-each-ref','--format=%(refname)','refs/heads/private']),'');
  const reachable=git(target,['rev-list','--objects','--all']).split('\n').map(x=>x.split(' ')[0]);
  assert.ok(reachable.includes(sourceOld));assert.ok(!reachable.includes(old));
  git(target,['pack-objects',join(target,'objects/pack/pack')],reachable.join('\n')+'\n');
  unlinkSync(join(target,'objects/info/alternates'));
  git(target,['fsck','--full','--no-dangling']);
  assert.throws(()=>git(target,['cat-file','-e',old]));
  assert.equal(readFileSync(join(source,'generated.bin'),'utf8'),'unused generated');
});
