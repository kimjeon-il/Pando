import test from 'node:test';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {mkdtempSync,mkdirSync,writeFileSync,readFileSync,rmSync,unlinkSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join,dirname} from 'node:path';
import {buildHistoryRetentionManifest,rewriteHistory} from "../../tools/data/library-history.mjs";

test('selected refs retain source history, remove superseded generated bytes and exclude private refs',async t=>{
  const base=mkdtempSync(join(tmpdir(),'pando-retention-fixture-'));
  t.after(()=>rmSync(base,{recursive:true,force:true}));
  const source=join(base,'source'),target=join(base,'clean.git');mkdirSync(source);
  const git=(root,args,input)=>execFileSync('git',['-C',root,'-c','gc.auto=0','-c','core.autocrlf=false',...args],{input,encoding:'utf8',stdio:['pipe','pipe','pipe']}).trim();
  const put=(path,value)=>{mkdirSync(dirname(join(source,path)),{recursive:true});writeFileSync(join(source,path),value);};
  const commit=()=>{git(source,['add','.']);git(source,['commit','-qm','edition']);};
  git(source,['init','-q','-b','main']);git(source,['config','user.name','Fixture']);git(source,['config','user.email','fixture@example.invalid']);
  put('src/input.txt','source v1');put('generated.bin','old generated');put('retired.bin','retired bytes');commit();
  const sourceOld=git(source,['rev-parse','HEAD:src/input.txt']),old=git(source,['rev-parse','HEAD:generated.bin']);
  put('src/input.txt','source v2');put('generated.bin','current generated');commit();
  const current=git(source,['rev-parse','HEAD:generated.bin']);git(source,['branch','work/live']);
  put('generated.bin','unused generated');commit();git(source,['branch','private']);
  const manifest=buildHistoryRetentionManifest({keepPaths:['src/input.txt','generated.bin'],indexes:[],allowedBlobIds:{'generated.bin':[current]}});
  await rewriteHistory({source,target,manifest,refs:['refs/heads/main','refs/heads/work/live']});
  assert.equal(git(target,['ls-tree','--name-only','main','--','generated.bin']),'');
  assert.equal(git(target,['rev-parse','work/live:generated.bin']),current);
  assert.equal(git(target,['for-each-ref','--format=%(refname)','refs/heads/private']),'');
  const reachable=git(target,['rev-list','--objects','--all']).split('\n').map(x=>x.split(' ')[0]);
  assert.ok(reachable.includes(sourceOld));assert.ok(!reachable.includes(old));
  git(target,['pack-objects',join(target,'objects/pack/pack')],reachable.join('\n')+'\n');
  unlinkSync(join(target,'objects/info/alternates'));
  git(target,['fsck','--full','--no-dangling']);
  assert.throws(()=>git(target,['cat-file','-e',old]));
  assert.equal(readFileSync(join(source,'generated.bin'),'utf8'),'unused generated');
});

test('renamed Unicode paths, merge parents, annotated tags and multiline messages survive streaming', async t => {
  const base=mkdtempSync(join(tmpdir(),'pando-history-paths-'));
  t.after(()=>rmSync(base,{recursive:true,force:true}));
  const source=join(base,'source'),target=join(base,'clean.git');mkdirSync(source);
  const git=(root,args)=>execFileSync('git',['-C',root,'-c','gc.auto=0','-c','core.autocrlf=false',...args],{encoding:'utf8',stdio:['pipe','pipe','pipe']}).trim();
  git(source,['init','-q','-b','main']);git(source,['config','user.name','Fixture']);git(source,['config','user.email','fixture@example.invalid']);
  writeFileSync(join(source,'한 글.txt'),'original bytes');mkdirSync(join(source,'retired'));writeFileSync(join(source,'retired/old.bin'),'obsolete');git(source,['add','.']);
  git(source,['commit','-qm','first\n\nM 100644 looks like a file command']);
  git(source,['checkout','-qb','side']);writeFileSync(join(source,'side.txt'),'side');git(source,['add','.']);git(source,['commit','-qm','side']);
  git(source,['checkout','-q','main']);writeFileSync(join(source,'main.txt'),'main');git(source,['add','.']);git(source,['commit','-qm','main']);
  git(source,['merge','--no-ff','-qm','merge both','side']);git(source,['tag','-a','release','-m','annotated tag']);
  git(source,['update-ref','refs/pull/1/head','main']);
  const manifest=buildHistoryRetentionManifest({keepPaths:['한 글.txt','side.txt','main.txt','retired/old.bin'],indexes:[]});
  manifest.excludedPrefixes=['retired/'];
  await rewriteHistory({source,target,manifest,renamePaths:{'한 글.txt':'이름 바뀜.txt'}});
  assert.equal(git(target,['show','main:이름 바뀜.txt']),'original bytes');
  assert.equal(git(target,['ls-tree','-r','--name-only','main','--','한 글.txt']),'');
  assert.equal(git(target,['log','--all','--format=%H','--','retired/']),'');
  assert.equal(git(target,['rev-list','--parents','-n','1','main']).split(' ').length,3);
  assert.equal(git(target,['cat-file','-t','refs/tags/release']),'tag');
  assert.match(git(target,['log','--format=%B','--all']),/M 100644 looks like a file command/);
  const { summarizeHistoryAudit } = await import("../../tools/data/git-history-dryrun.mjs");
  const summary = summarizeHistoryAudit({original:source,filtered:target,repo:'fixture',obsoletePath:'retired/old.bin',obsoletePrefix:'retired/',beforeBytes:100,afterBytes:40});
  assert.equal(summary.pull_ref_count,1);
  assert.equal(summary.pull_refs_with_obsolete_path_on_tip,1);
  assert.equal(summary.obsolete_path_remains_in_filtered_history,false);
  assert.equal(summary.nominal_repacked_difference_bytes,60);
  git(target,['fsck','--full','--no-dangling']);
});
