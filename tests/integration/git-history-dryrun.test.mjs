import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, readFileSync, rmSync, unlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import test from 'node:test';

test('audit CLI rewrites only its isolated copy and records ref and size evidence', t => {
  const root=mkdtempSync(join(tmpdir(),'pando-audit-fixture-'));
  t.after(()=>rmSync(root,{recursive:true,force:true}));
  const original=join(root,'original.git'), filtered=join(root,'filtered.git'), evidence=join(root,'evidence');
  mkdirSync(original);mkdirSync(evidence);
  const git=(cwd,...args)=>execFileSync('git',['-C',cwd,'-c','gc.auto=0','-c','core.autocrlf=false',...args],{encoding:'utf8',stdio:['pipe','pipe','pipe']}).trim();
  git(original,'init','-q','-b','main');git(original,'config','user.name','Fixture');git(original,'config','user.email','fixture@example.invalid');
  const retired='assets/data/terrain/v0.12.0';mkdirSync(join(original,retired),{recursive:true});
  writeFileSync(join(original,retired,'manifest.json'),'old terrain');writeFileSync(join(original,'retained.txt'),'live');
  git(original,'add','.');git(original,'commit','-qm','old terrain');git(original,'update-ref','refs/pull/1/head','main');
  const before=git(original,'rev-parse','main');
  const env={...process.env,AUDIT_DIR:root,GITHUB_REPOSITORY:'fixture/project',GITHUB_SHA:before};
  execFileSync(process.execPath,['tools/data/git-history-dryrun.mjs','rewrite'],{env,stdio:'pipe'});
  git(filtered,'repack','-a','-d');unlinkSync(join(filtered,'objects/info/alternates'));
  git(filtered,'fsck','--full','--no-dangling');
  writeFileSync(join(evidence,'original-objects-bytes.txt'),'100\n');writeFileSync(join(evidence,'filtered-objects-bytes.txt'),'40\n');
  execFileSync(process.execPath,['tools/data/git-history-dryrun.mjs','summarize'],{env,stdio:'pipe'});
  const summary=JSON.parse(readFileSync(join(evidence,'summary.json'),'utf8'));
  assert.equal(summary.original_main,before);assert.equal(summary.pull_ref_count,1);
  assert.equal(summary.pull_refs_with_obsolete_path_on_tip,1);assert.deepEqual(summary.missing_refs,[]);
  assert.equal(summary.nominal_repacked_difference_bytes,60);assert.equal(summary.obsolete_path_remains_in_filtered_history,false);
  assert.equal(git(filtered,'show','main:retained.txt'),'live');
  assert.equal(git(original,'show',`main:${retired}/manifest.json`),'old terrain');
  assert.equal(git(original,'rev-parse','main'),before);
});
