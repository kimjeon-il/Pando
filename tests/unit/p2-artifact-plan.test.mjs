import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import test from 'node:test';
import { sharedSourceManifest } from '../../tools/package-shared-core-assets.mjs';
import { wasmStatus, generatedStatus, selectJobs, assertSafeGeneratedPaths,
  plan } from '../../scripts/p2-artifact-plan.mjs';

const digest=bytes=>createHash('sha256').update(bytes).digest('hex');
const bytes=t=>Buffer.isBuffer(t)?t:Buffer.from(t);
function fixture(t) {
  const root=mkdtempSync(join(tmpdir(),'pando-p2-'));
  t.after(()=>rmSync(root,{recursive:true,force:true}));
  const put=(p,b)=>{const file=join(root,p);mkdirSync(dirname(file),{recursive:true});writeFileSync(file,b);};
  const get=p=>readFileSync(join(root,p));
  put('config/toolchain-versions.json',JSON.stringify({emscripten:'4.0.20'}));
  put('shared/CMakeLists.txt','project(Shared)\n');
  put('shared/core/src/calc.cpp','int calc=1;\n');
  const identity=sharedSourceManifest(root);
  put('assets/wasm/pandoeditor-core.js','export default()=>{};\n');
  put('assets/wasm/pandoeditor-core.wasm',Buffer.from([0,97,115,109,1,0,0,0]));
  put('assets/wasm/pandoeditor-core.manifest.json',JSON.stringify({
    schema:'pandoeditor-core-wasm',abiVersion:1,sourceSha256:identity.sourceSha256,
    compiler:{name:'emscripten',version:'4.0.20'},inputs:identity.inputs,
    assets:{
      js:{file:'pandoeditor-core.js',sha256:digest(get('assets/wasm/pandoeditor-core.js'))},
      wasm:{file:'pandoeditor-core.wasm',sha256:digest(get('assets/wasm/pandoeditor-core.wasm'))}
    }
  }));
  put('assets/js/modules/geometry.js','const n=1;\n');
  put('native/assets/geometry/current/cut/geometry.js','const n=1;\n');
  put('native/resources/current_geometry.qrc','<RCC/>\n');
  put('native/assets/geometry/current/manifest.json',JSON.stringify({
    schemaVersion:2,sourceEncoding:'UTF-8 LF',
    files:[{path:'assets/js/modules/geometry.js',sha256:digest(get('assets/js/modules/geometry.js'))}],
    artifacts:[{path:'native/assets/geometry/current/cut/geometry.js',
      sha256:digest(get('native/assets/geometry/current/cut/geometry.js'))}]
  }));
  put('native/app/reference-web/adapter.js','const r=1;\n');
  put('native/app/reference-web/runtime.js','const r=1;\n');
  put('native/app/reference-web/manifest.json',JSON.stringify({
    schemaVersion:2,sourceEncoding:'UTF-8 LF',
    files:[{path:'native/app/reference-web/adapter.js',
      sha256:digest(get('native/app/reference-web/adapter.js'))}],
    runtime:{path:'native/app/reference-web/runtime.js',
      sha256:digest(get('native/app/reference-web/runtime.js'))}
  }));
  return {root,put,get};
}
test('current coherent source, generated bytes and dependency lists skip all compilers',t=>{
  const f=fixture(t), result=plan(f.root);
  assert.deepEqual(['wasm','geometry','reference'].map(k=>result[k]),[false,false,false]);
  assert.equal(result.statuses.wasm.sourceSha256,sharedSourceManifest(f.root).sourceSha256);
});
test('a changed C++ input only invalidates its compiled WASM pair',t=>{
  const f=fixture(t);f.put('shared/core/src/calc.cpp','int calc=2;\n');
  const p=plan(f.root);
  assert.equal(p.wasm,true);assert.equal(p.geometry,false);assert.equal(p.reference,false);
  assert.match(p.statuses.wasm.reasons.join(';'),/source fingerprint/);
});
test('missing or corrupted WASM runtime cannot be called up to date',t=>{
  const f=fixture(t);f.put('assets/wasm/pandoeditor-core.wasm','corrupt');
  assert.equal(wasmStatus(f.root).needed,true);
  assert.match(wasmStatus(f.root).reasons.join(';'),/wasm bytes\/hash/);
});
test('stale active Qt JavaScript source only regenerates Qt geometry',t=>{
  const f=fixture(t);f.put('assets/js/modules/geometry.js','const n=2;\n');
  assert.equal(plan(f.root).geometry,true);
  assert.equal(plan(f.root).wasm,false);assert.equal(plan(f.root).reference,false);
  assert.match(generatedStatus(f.root,'geometry','native/assets/geometry/current/manifest.json').reasons[0],/source/);
});
test('stale reference bundle does not cause an unrelated WASM or Qt geometry rebuild',t=>{
  const f=fixture(t);f.put('native/app/reference-web/runtime.js','broken');
  const p=plan(f.root);
  assert.equal(p.reference,true);assert.equal(p.wasm,false);assert.equal(p.geometry,false);
});
test('manifest references outside the repository are never read',t=>{
  const f=fixture(t);
  f.put('native/app/reference-web/manifest.json',JSON.stringify({
    schemaVersion:2,sourceEncoding:'UTF-8 LF',files:[{path:'../elsewhere.js',sha256:'a'.repeat(64)}],
    runtime:{path:'native/app/reference-web/runtime.js',sha256:'a'.repeat(64)}
  }));
  assert.equal(plan(f.root).reference,true);
});
test('scope overrides are explicit and bootstrap reruns only the controlled generators',()=>{
  const fresh={wasm:{needed:false},geometry:{needed:false},reference:{needed:false}};
  assert.deepEqual(['wasm','geometry','reference'].map(k=>selectJobs(fresh,[], 'auto')[k]),[false,false,false]);
  assert.deepEqual(['wasm','geometry','reference'].map(k=>selectJobs(fresh,[], 'geometry')[k]),[false,true,false]);
  assert.equal(selectJobs(fresh,['.github/workflows/generated-artifacts-p2.yml']).bootstrap,true);
  assert.deepEqual(['wasm','geometry','reference'].map(k=>selectJobs(fresh,[], 'verify')[k]),[false,false,false]);
  assert.throws(()=>selectJobs(fresh,[],'unsupported'),/P2_INVALID_SCOPE/);
});
test('publishing is limited to declared generated artifacts, not source or test fixtures',()=>{
  assertSafeGeneratedPaths(['assets/wasm/pandoeditor-core.js',
    'native/assets/geometry/current/cut/example.js',
    'native/resources/current_geometry.qrc',
    'native/app/reference-web/runtime.js'],{wasm:true,geometry:true,reference:true});
  assert.throws(()=>assertSafeGeneratedPaths(['shared/core/src/project.cpp'],{wasm:true}),/P2_UNEXPECTED_GENERATED_FILE/);
  assert.throws(()=>assertSafeGeneratedPaths(['assets/wasm/pandoeditor-core.wasm'],{wasm:false}),/P2_UNEXPECTED_GENERATED_FILE/);
  assert.throws(()=>assertSafeGeneratedPaths(['native/assets/geometry/cut/original/a.js'],{geometry:true}),/P2_UNEXPECTED_GENERATED_FILE/);
});
