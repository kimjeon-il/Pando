import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,readFileSync,writeFileSync,rmSync,existsSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {execFileSync} from 'node:child_process';
import {compactDuplicatePacks,repackLocalObjects,localObjects,snapshotGitStorage} from '../../../tools/data/library-git.mjs';
const git=(r,args,input)=>execFileSync('git',['-c','gc.auto=0',...args],{cwd:r,encoding:'utf8',input,stdio:'pipe'}).trim();
test('installed compaction recovers only additive objects without losing original or newly discovered bytes',t=>{
 const root=mkdtempSync(join(tmpdir(),'pando-additive-repack-'));t.after(()=>rmSync(root,{recursive:true,force:true}));
 git(root,['init','-q']);git(root,['config','user.name','Fixture']);git(root,['config','user.email','fixture@example.invalid']);writeFileSync(join(root,'file'),'retained');git(root,['add','.']);git(root,['commit','-qm','fixture']);
 const original=git(root,['hash-object','-w','--stdin'],'unreachable original');git(root,['repack','-ad']);
 const journal=snapshotGitStorage(root),pending=join(root,'.git/pando-git-compaction.pending.json');
 let added;
 const save=()=>{writeFileSync(pending,JSON.stringify(journal));if(journal.phase==='packs-installed'&&!added)added=git(root,['hash-object','-w','--stdin'],'concurrent local bytes');};
 save();assert.throws(()=>repackLocalObjects(root,journal,save),/Local objects missing after pack replacement/);
 assert.equal(git(root,['cat-file','-p',original]),'unreachable original');assert.equal(git(root,['cat-file','-p',added]),'concurrent local bytes');
 const expected=localObjects(root);
 assert.throws(()=>compactDuplicatePacks(root),/explicit recovery/);
 const originalJournal=readFileSync(pending),missing=JSON.parse(originalJournal);
 missing.objects.push({oid:'f'.repeat(40),type:'blob',bytes:1});writeFileSync(pending,JSON.stringify(missing));
 const missingBytes=readFileSync(pending);
 assert.throws(()=>compactDuplicatePacks(root,{recoverAdditions:true}),/explicit recovery|Missing local objects/);
 assert.deepEqual(readFileSync(pending),missingBytes,'missing objects cannot be waived or rewritten');
 writeFileSync(pending,originalJournal);
 compactDuplicatePacks(root,{recoverAdditions:true});
 assert.deepEqual(localObjects(root),expected);
 assert.equal(git(root,['cat-file','-p',original]),'unreachable original');assert.equal(git(root,['cat-file','-p',added]),'concurrent local bytes');assert.equal(existsSync(pending),false);
});
