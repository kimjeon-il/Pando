import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { auditTerritorialStorage, unclassifiedTerritorialAccesses } from './lib/territorial-storage-audit.mjs';

const root = process.cwd();
function sources(directory) {
  return fs.readdirSync(path.join(root, directory), { withFileTypes: true }).flatMap(entry => {
    const file = `${directory}/${entry.name}`;
    return entry.isDirectory() ? sources(file) : entry.name.endsWith('.js') ? [file] : [];
  });
}
const entries = sources('assets/js').flatMap(file => auditTerritorialStorage(fs.readFileSync(path.join(root, file), 'utf8'), file));
if (process.argv.includes('--inventory')) {
  console.log(JSON.stringify(entries, null, 2));
} else {
  const policy = JSON.parse(fs.readFileSync(path.join(root, 'scripts/contracts/territorial-storage-access.json'), 'utf8'));
  const failures = unclassifiedTerritorialAccesses(entries, policy);
  if (failures.length) {
    for (const entry of failures) console.error(`${entry.file}:${entry.line} ${entry.function} ${entry.access}: ${entry.expression}`);
    console.error(`Territorial storage audit failed: ${failures.length} unclassified/forbidden accesses.`);
    process.exitCode = 1;
  } else {
    console.log(`Territorial storage audit passed: ${entries.length} classified accesses; no unclassified or forbidden writes.`);
    if (process.argv.includes('--write-report')) {
      const classified = entries.map(entry => ({ ...entry,
        classification: policy.owners.find(item => item.file === entry.file && item.functions.includes(entry.function)),
      }));
      fs.mkdirSync(path.join(root, 'reports/territorial-integration'), { recursive: true });
      fs.writeFileSync(path.join(root, 'reports/territorial-integration/storage-access.json'), JSON.stringify(classified, null, 2) + '\n');
      const escape = value => String(value).replaceAll('|', '\\|').replace(/\s+/g, ' ');
      const rows = classified.map(entry => `| [${entry.file}:${entry.line}](../../${entry.file}#L${entry.line}) | ${entry.function} | ${entry.access} | ${entry.field} / ${entry.via} | ${escape(entry.classification.owner)} | ${escape(entry.classification.reason)} | ${escape(entry.expression)} |`);
      fs.writeFileSync(path.join(root, 'reports/territorial-integration/storage-access.md'),
        '# Territorial storage access inventory\n\nGenerated by node scripts/check-territorial-storage.mjs --write-report.\n\n'
        + 'Each row is classified by exact file and function, not by whole-file exemption. See final-gate.md for call-path review, changes and static-analysis limits.\n\n'
        + '| File/line | Function | Access | Field / route | Owner/call boundary | Reason | Expression |\n'
        + '| --- | --- | --- | --- | --- | --- | --- |\n' + rows.join('\n') + '\n');
    }
  }
}
